// node --test src/*.test.ts (npm test here): Vibe mode is gone (#760, Marco 2026-11-09: "remove vibe"), and nothing
// replaces it. No page of the face is built for it (vite.config.ts build.rollupOptions.input), Settings has no row
// or section for it, and the shell has no command or capability for it.
import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join, resolve } from "node:path";

const mac = resolve(import.meta.dirname, "..");
const read = (p: string) => readFileSync(join(mac, p), "utf8");

test("no Vite input names vibe", () => {
  const m = /rollupOptions:\s*\{\s*input:\s*\{([^}]*)\}/.exec(read("vite.config.ts"));
  assert.ok(m, "vite.config.ts has build.rollupOptions.input");
  assert.doesNotMatch(m[1], /vibe/i);
  assert.ok(!existsSync(join(mac, "vibe.html")), "vibe.html is gone");
});

test("no Settings row or section names vibe, and Settings has no music section", () => {
  for (const f of ["src/Settings.tsx", "src/settingsShell.tsx"]) assert.doesNotMatch(read(f), /vibe/i, `${f} names vibe`);
  // SECTIONS (settingsShell.tsx, a .tsx node cannot load): its keys, read from the source
  const m = /export const SECTIONS[^=]*=\s*\{([\s\S]*?)\n\};/.exec(read("src/settingsShell.tsx"));
  assert.ok(m, "settingsShell.tsx has SECTIONS");
  const keys = [...m[1].matchAll(/^\s*"([^"]+)":\s*\{/gm)].map((x) => x[1]);
  assert.ok(keys.includes("look"), "SECTIONS was read (it has look)");
  assert.ok(!keys.includes("music"), "SECTIONS has no music key");
});

test("the seat scene, Work and the shell's hot reload name no vibe", () => {
  for (const f of ["src/SeatScene.tsx", "src/work/WorkApp.tsx", "src-tauri/src/hot.rs"]) assert.doesNotMatch(read(f), /vibe/i, `${f} names vibe`);
});

test("the shell has no vibe command, permission or capability", () => {
  assert.doesNotMatch(read("src-tauri/build.rs"), /vibe/i);
  assert.doesNotMatch(read("src-tauri/src/lib.rs"), /vibe/i);
  for (const d of ["src-tauri/capabilities", "src-tauri/permissions/autogenerated"]) {
    const dir = join(mac, d);
    if (!existsSync(dir)) continue;
    for (const f of readdirSync(dir)) {
      assert.doesNotMatch(f, /vibe/i, `${d}/${f}`);
      assert.doesNotMatch(readFileSync(join(dir, f), "utf8"), /vibe/i, `${d}/${f} names vibe`);
    }
  }
});
